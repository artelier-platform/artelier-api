package com.artelier.api.dto.request;

import com.fasterxml.jackson.annotation.JsonProperty;
import io.swagger.v3.oas.annotations.media.Schema;

import java.util.List;

/**
 * Webhook payload received from Wompi when the state of a transaction changes.
 *
 * <p>Only the fields the API needs are mapped; any other field sent by Wompi
 * is ignored.</p>
 *
 * @param event     Wompi event type; only {@code transaction.updated} is processed
 * @param data      wrapper of the transaction payload
 * @param signature data used to validate the authenticity of the webhook
 * @param timestamp Unix timestamp of the event, as sent by Wompi
 */
@Schema(
        name = "PaymentWebhookRequest",
        description = "Webhook payload received from Wompi when the state of a transaction changes"
)
public record PaymentWebhookRequest(

        @Schema(
                description = "Wompi event type. Only transaction.updated is processed.",
                example = "transaction.updated"
        )
        String event,

        @Schema(description = "Wrapper of the transaction payload")
        TransactionData data,

        @Schema(description = "Signature data used to validate the authenticity of the webhook")
        SignatureData signature,

        @Schema(description = "Unix timestamp of the event, as sent by Wompi", example = "1715000000000")
        Long timestamp

) {

    /**
     * Wrapper of the transaction.
     *
     * @param transaction transaction detail
     */
    @Schema(description = "Wrapper of the transaction")
    public record TransactionData(

            @Schema(description = "Transaction detail")
            Transaction transaction

    ) {}

    /**
     * Wompi transaction data.
     *
     * @param id                Wompi transaction identifier
     * @param reference         merchant reference sent when the payment was created
     * @param status            transaction status
     * @param paymentMethodType payment method used by the customer
     * @param amountInCents     amount of the transaction, in cents
     */
    @Schema(description = "Wompi transaction data")
    public record Transaction(

            @Schema(description = "Unique transaction ID in Wompi", example = "1292-1602113476-10985")
            String id,

            @Schema(description = "Merchant reference", example = "ORDER-550e8400-1715000000000")
            String reference,

            @Schema(
                    description = "Transaction status",
                    example = "APPROVED",
                    allowableValues = {"PENDING", "APPROVED", "DECLINED", "VOIDED", "ERROR"}
            )
            String status,

            @Schema(
                    description = "Payment method used by the customer",
                    example = "NEQUI",
                    allowableValues = {"CARD", "NEQUI", "PSE", "BANCOLOMBIA_TRANSFER", "BANCOLOMBIA_QR"}
            )
            @JsonProperty("payment_method_type")
            String paymentMethodType,

            @Schema(description = "Amount in cents", example = "100000")
            @JsonProperty("amount_in_cents")
            Long amountInCents

    ) {}

    /**
     * Signature block used to verify the authenticity of the webhook.
     *
     * @param checksum   SHA-256 checksum generated by Wompi
     * @param properties transaction properties used to generate the checksum
     */
    @Schema(description = "Signature block used to verify the authenticity of the webhook")
    public record SignatureData(

            @Schema(description = "SHA-256 checksum generated by Wompi", example = "a3f5c9d8e1b2...")
            String checksum,

            @Schema(
                    description = "Transaction properties used to generate the checksum",
                    example = "[\"transaction.id\", \"transaction.status\", \"transaction.amount_in_cents\"]"
            )
            List<String> properties

    ) {}
}
